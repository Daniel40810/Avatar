-- Regler mit Bereich und Vorgabe, sortiert wie im Studio
CREATE OR REPLACE VIEW AV_REGLER_V AS
SELECT r.NAME, r.GRUPPE, r.BEZEICHNUNG, r.MIN_WERT, r.MAX_WERT, r.VORGABE, r.MORPHZIEL, r.REIHENFOLGE, r.HERKUNFT, r.VERSION
  FROM AV_REGLER r;

-- Gefühle mit ihrer Mischung der Gesichtsformen als JSON
CREATE OR REPLACE VIEW AV_GEFUEHL_V AS
SELECT g.NAME, g.VALENZ, g.ERREGUNG, g.KOPF_SENKEN, g.BLICK_SENKEN, g.KOPF_NEIGEN, g.SCHULTERN,
       g.LIDSCHLAG, g.ATEM_TAKT, g.ATEM_TIEFE, g.SAKKADEN, g.ABWENDEN, g.REIHENFOLGE, g.HERKUNFT,
       (SELECT JSON_OBJECTAGG(f.FORM VALUE f.GEWICHT RETURNING VARCHAR2(4000)) FROM AV_GEFUEHL_FORM f WHERE f.GEFUEHL_ID = g.ID) AS FORMEN
  FROM AV_GEFUEHL g;

-- Outfits mit ihren Stücken, je Stück eine Zeile
CREATE OR REPLACE VIEW AV_OUTFIT_V AS
SELECT o.NAME AS OUTFIT, o.BEZEICHNUNG, t.REIHENFOLGE, t.NETZ, k.BEZEICHNUNG AS STUECK, k.ART, t.STOFF, s.BEZEICHNUNG AS STOFF_BEZEICHNUNG,
       t.FARBE_R, t.FARBE_G, t.FARBE_B, o.HERKUNFT
  FROM AV_OUTFIT o
  JOIN AV_OUTFIT_TEIL t ON t.OUTFIT_ID = o.ID
  JOIN AV_KLEIDUNG k ON k.NETZ = t.NETZ
  LEFT JOIN AV_STOFF s ON s.NAME = t.STOFF;

-- Rollen mit Kleiderart und Epoche
CREATE OR REPLACE VIEW AV_ROLLE_V AS
SELECT r.NAME, r.BEZEICHNUNG, r.KLEIDERART, r.EPOCHE, e.BEZEICHNUNG AS EPOCHE_BEZEICHNUNG, r.SZENE, r.HERKUNFT
  FROM AV_ROLLE r
  JOIN AV_EPOCHE e ON e.NAME = r.EPOCHE;

-- Presets mit den wichtigsten Reglern ausgeklappt
CREATE OR REPLACE VIEW AV_PRESET_V AS
SELECT p.NAME, p.PERSON.SEED AS SEED, p.PERSON.NAME AS PERSON_NAME, p.PERSON.GESCHLECHT AS GESCHLECHT, p.PERSON.ALTER_J AS ALTER_J,
       JSON_VALUE(p.PERSON.REGLER, '$.hair') AS FRISUR,
       JSON_VALUE(p.PERSON.REGLER, '$.melanin' RETURNING NUMBER) AS MELANIN,
       JSON_VALUE(p.PERSON.REGLER, '$.iris' RETURNING NUMBER) AS IRIS,
       p.OUTFIT, p.BEMERKUNG, p.HERKUNFT, p.PERSON.REGLER AS REGLER
  FROM AV_PRESET p;

-- -----------------------------------------------------------------------------------------------------
-- Metadaten: jedes Schema sieht in USER_AV_METADATA nur seine eigenen Anmeldungen und schreibt dort hinein;
-- ALL_AV_METADATA zeigt alle (welches Projekt welche Avatare nutzt).
-- -----------------------------------------------------------------------------------------------------
CREATE OR REPLACE VIEW USER_AV_METADATA AS
SELECT m.TABELLE AS TABLE_NAME, m.SPALTE AS COLUMN_NAME, m.ROLLE, m.BEMERKUNG, m.ANGELEGT, m.GEAENDERT
  FROM AV_METADATA m
 WHERE m.SCHEMA_NAME = SYS_CONTEXT('USERENV', 'SESSION_USER');

CREATE OR REPLACE VIEW ALL_AV_METADATA AS
SELECT m.SCHEMA_NAME AS OWNER, m.TABELLE AS TABLE_NAME, m.SPALTE AS COLUMN_NAME, m.ROLLE, m.BEMERKUNG, m.ANGELEGT, m.GEAENDERT
  FROM AV_METADATA m;

CREATE OR REPLACE TRIGGER AV_USER_METADATA_IOT
INSTEAD OF INSERT OR UPDATE OR DELETE ON USER_AV_METADATA
FOR EACH ROW
DECLARE
  S VARCHAR2(128) := SYS_CONTEXT('USERENV', 'SESSION_USER');
BEGIN
  IF INSERTING THEN
    INSERT INTO AV_METADATA (SCHEMA_NAME, TABELLE, SPALTE, ROLLE, BEMERKUNG)
    VALUES (S, :NEW.TABLE_NAME, :NEW.COLUMN_NAME, :NEW.ROLLE, :NEW.BEMERKUNG);
  ELSIF UPDATING THEN
    UPDATE AV_METADATA
       SET TABELLE = :NEW.TABLE_NAME, SPALTE = :NEW.COLUMN_NAME, ROLLE = :NEW.ROLLE, BEMERKUNG = :NEW.BEMERKUNG
     WHERE SCHEMA_NAME = S AND TABELLE = UPPER(:OLD.TABLE_NAME) AND SPALTE = UPPER(:OLD.COLUMN_NAME);
  ELSE
    DELETE FROM AV_METADATA
     WHERE SCHEMA_NAME = S AND TABELLE = UPPER(:OLD.TABLE_NAME) AND SPALTE = UPPER(:OLD.COLUMN_NAME);
  END IF;
END;
