-- der Sicht (04_sichten.sql), immer mit dem Schema der Sitzung.
-- =====================================================================================================
CREATE SEQUENCE AV_METADATA_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE AV_METADATA (
  ID          NUMBER(10) NOT NULL,
  SCHEMA_NAME VARCHAR2(128) NOT NULL,
  TABELLE     VARCHAR2(128) NOT NULL,
  SPALTE      VARCHAR2(128) NOT NULL,
  ROLLE       VARCHAR2(30 CHAR),
  BEMERKUNG   VARCHAR2(400 CHAR),
  ANGELEGT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  GEAENDERT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT AV_METADATA_PK PRIMARY KEY (ID),
  CONSTRAINT AV_METADATA_UK UNIQUE (SCHEMA_NAME, TABELLE, SPALTE)
);

CREATE OR REPLACE TRIGGER AV_METADATA_BIU
BEFORE INSERT OR UPDATE ON AV_METADATA
FOR EACH ROW
BEGIN
  IF INSERTING AND :NEW.ID IS NULL THEN
    :NEW.ID := AV_METADATA_SEQ.NEXTVAL;
  END IF;
  :NEW.SCHEMA_NAME := UPPER(:NEW.SCHEMA_NAME);
  :NEW.TABELLE := UPPER(:NEW.TABELLE);
  :NEW.SPALTE := UPPER(:NEW.SPALTE);
  :NEW.GEAENDERT := SYSTIMESTAMP;
END;
