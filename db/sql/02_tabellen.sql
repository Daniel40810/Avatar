-- AV_SCHEMA: Ausbaustufe, eine Zeile je Stufe (F37). Phase 14 = 1.
CREATE TABLE AV_SCHEMA (
  VERSION      NUMBER(4) NOT NULL,
  EINGERICHTET TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  APP_VERSION  VARCHAR2(20 CHAR) NOT NULL,
  TEXT         VARCHAR2(400 CHAR),
  CONSTRAINT AV_SCHEMA_PK PRIMARY KEY (VERSION)
);

-- AV_LOG: Protokoll des Schemas (Einrichten, Fehler der API, Anmeldungen). NUTZER ist das Schema, das schrieb.
CREATE SEQUENCE AV_LOG_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE AV_LOG (
  ID     NUMBER(12) NOT NULL,
  ZEIT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  STUFE  VARCHAR2(8) DEFAULT 'INFO' NOT NULL,
  QUELLE VARCHAR2(60 CHAR),
  TEXT   VARCHAR2(2000 CHAR),
  NUTZER VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV', 'SESSION_USER') NOT NULL,
  CONSTRAINT AV_LOG_PK PRIMARY KEY (ID),
  CONSTRAINT AV_LOG_STUFE_CK CHECK (STUFE IN ('INFO', 'WARNUNG', 'FEHLER'))
);

CREATE OR REPLACE TRIGGER AV_LOG_BI
BEFORE INSERT ON AV_LOG
FOR EACH ROW
BEGIN
  IF :NEW.ID IS NULL THEN
    :NEW.ID := AV_LOG_SEQ.NEXTVAL;
  END IF;
END;
/

CREATE INDEX AV_LOG_ZEIT_IX ON AV_LOG (ZEIT);

