  GEAENDERT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT AV_PRESET_PK PRIMARY KEY (ID),
  CONSTRAINT AV_PRESET_UK UNIQUE (NAME),
  CONSTRAINT AV_PRESET_OUTFIT_FK FOREIGN KEY (OUTFIT) REFERENCES AV_OUTFIT (NAME),
  CONSTRAINT AV_PRESET_HERKUNFT_CK CHECK (HERKUNFT IN ('MITGELIEFERT', 'EIGEN'))
);

CREATE OR REPLACE TRIGGER AV_PRESET_BIU
BEFORE INSERT OR UPDATE ON AV_PRESET
FOR EACH ROW
BEGIN
  IF INSERTING AND :NEW.ID IS NULL THEN
    :NEW.ID := AV_PRESET_SEQ.NEXTVAL;
  END IF;
  :NEW.GEAENDERT := SYSTIMESTAMP;
END;
