-- =====================================================================================================
-- Avatar · Datenbank · 02_tabellen.sql
-- Schema AVATAR auf PDBORCL, Präfix AV_. Werkbuch Abschnitt 8 (Zuschnitt), F29–F40 „alle A“.
--
-- AVATAR ist ein Dienst-Schema wie MDSYS (F29 A): Typen, Packages, Kataloge und Metadaten. Personen der Projekte
-- stehen in deren eigenen Tabellen (Spalte vom Typ AV_PERSON_T); hier stehen nur die mitgelieferten und die im
-- Studio gespeicherten Presets. Geometrie, Texturen und Shader bleiben Ressourcen im Package (F36 A); die
-- Datenbank kennt Schlüssel, Parameter und Prüfsummen.
--
-- Wiederholbar: Was schon da ist, meldet Oracle mit ORA-00955 (Name schon vergeben); der Einrichter übergeht genau
-- diese Meldung und trägt fehlende Spalten nach. Dieses Skript löscht nichts. In SQL Developer als Skript (F5).
--
-- Hauskonvention: ID aus Sequence + Trigger, nie GENERATED AS IDENTITY. Je Spalte eine Zeile. Jede Katalogzeile hat
-- HERKUNFT: MITGELIEFERT (stellt der Einrichter wieder her) oder EIGEN (fasst er nie an), dazu VERSION (F37).
-- 19 Tabellen in fünf Themen: Betrieb (3), Kataloge (10), Kleidung (4), Presets (1), Metadaten (1).
-- =====================================================================================================


